USE master;
IF DB_ID('AlunosTechHubDb') IS NULL
BEGIN
    CREATE DATABASE AlunosTechHubDb;
END;
GO
USE AlunosTechHubDb;
GO
CREATE TABLE dbo.Clientes (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Nome NVARCHAR(200) NOT NULL,
    Documento NVARCHAR(50) NULL,
    Segmento NVARCHAR(100) NULL,
    Ativo BIT NOT NULL DEFAULT 1,
    CriadoEm DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
CREATE TABLE dbo.Servicos (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Nome NVARCHAR(200) NOT NULL,
    Descricao NVARCHAR(500) NULL,
    PrazoPadraoHoras INT NOT NULL DEFAULT 8,
    Ativo BIT NOT NULL DEFAULT 1
);
GO
CREATE TABLE dbo.Chamados (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Numero NVARCHAR(50) NOT NULL UNIQUE,
    Titulo NVARCHAR(200) NOT NULL,
    Descricao NVARCHAR(1000) NOT NULL,
    ClienteId UNIQUEIDENTIFIER NOT NULL,
    SolicitanteId UNIQUEIDENTIFIER NOT NULL,
    TecnicoId UNIQUEIDENTIFIER NULL,
    ServicoId UNIQUEIDENTIFIER NOT NULL,
    Status NVARCHAR(50) NOT NULL,
    Prioridade NVARCHAR(50) NOT NULL,
    DataAbertura DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    PrazoSla DATETIME2 NULL,
    RowVersion ROWVERSION NOT NULL
);
GO
CREATE INDEX IX_Chamados_Status ON dbo.Chamados(Status);
CREATE INDEX IX_Chamados_Tecnico ON dbo.Chamados(TecnicoId);
